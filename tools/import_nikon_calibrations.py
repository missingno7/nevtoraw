"""Import numeric RGB calibration matrices from locally installed Nikon DCPs.

Only UniqueCameraModel, ColorMatrix1/2 and CalibrationIlluminant1/2 are exported.
Rendering tables and proprietary profile payloads are never bundled.
"""
from pathlib import Path
import argparse
import hashlib
import json
import math
import re
import struct


def camera_key(model):
    key = "".join(c for c in model.upper() if c.isascii() and c.isalnum())
    if key.startswith("NIKON"):
        key = key[5:]
    if re.fullmatch(r"E[0-9]{4}", key):
        key = "COOLPIX" + key[1:]
    return key


def read_profile(path):
    data = path.read_bytes()
    if data[:2] not in (b"II", b"MM"):
        raise ValueError("not a TIFF/DCP header")
    order = "<" if data[:2] == b"II" else ">"
    def read(offset, count):
        if offset < 0 or offset + count > len(data):
            raise ValueError("truncated profile")
        return data[offset:offset + count]
    def unpack(offset, fmt):
        return struct.unpack(order + fmt, read(offset, struct.calcsize(order + fmt)))
    if unpack(2, "H")[0] not in (42, 0x4352):
        raise ValueError("unsupported TIFF/DCP version")
    offset = unpack(4, "I")[0]
    tags = {}
    for i in range(unpack(offset, "H")[0]):
        entry = offset + 2 + 12 * i
        tag, kind, count, value = unpack(entry, "HHII")
        if tag not in (50708, 50721, 50722, 50778, 50779):
            continue
        width = {2: 1, 3: 2, 10: 8}.get(kind)
        if width is None:
            raise ValueError("unexpected calibration tag type")
        payload = read(entry + 8 if count * width <= 4 else value, count * width)
        if kind == 2:
            values = payload.rstrip(b"\0").decode("utf-8")
        elif kind == 3:
            values = list(struct.unpack(order + "H" * count, payload))
        else:
            numbers = struct.unpack(order + "ii" * count, payload)
            if any(numbers[i] == 0 for i in range(1, len(numbers), 2)):
                raise ValueError("zero calibration denominator")
            values = [numbers[i] / numbers[i + 1] for i in range(0, len(numbers), 2)]
        tags[tag] = values
    unique = tags[50708]
    cm1, cm2 = tags[50721], tags[50722]
    if len(cm1) != 9 or len(cm2) != 9:
        return None  # CMYG/four-color profiles are outside the RGB Bayer pipeline.
    if not all(math.isfinite(v) for v in cm1 + cm2):
        raise ValueError("non-finite matrix")
    return dict(model=unique, cm1=cm1, cm2=cm2, illuminants=[tags[50778][0], tags[50779][0]])


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("profiles", type=Path, help="Adobe Standard DCP directory")
    args = parser.parse_args()
    repository = Path(__file__).resolve().parents[1]
    existing = (repository / "src/camera_profiles.inc").read_text(encoding="utf-8")
    known = {camera_key(model): unique for model, unique in re.findall(r'^\{"([^"]+)", "([^"]+)"', existing, re.M)}
    known[camera_key("Nikon Z 8")] = "Nikon Z 8"
    imported, skipped = {}, []
    for path in sorted(args.profiles.glob("*.dcp")):
        if not path.name.upper().startswith("NIKON"):
            continue
        profile = read_profile(path)
        if profile is None:
            skipped.append(path.name)
            continue
        key = camera_key(profile["model"])
        if key in known:
            continue  # Preserve previously sample-verified calibration and exposure metadata.
        profile.update(file=path.name, sha256=hashlib.sha256(path.read_bytes()).hexdigest())
        if key not in imported or " v2.dcp" in path.name.lower():
            imported[key] = profile
    if not imported:
        parser.error("no additional RGB Nikon profiles found")
    lines = ["// Numeric Nikon RGB calibrations from local Adobe Standard DCP metadata.",
             "// Generated by tools/import_nikon_calibrations.py; no rendering LUTs included."]
    for key, p in sorted(imported.items()):
        matrix = lambda values: "{" + ", ".join(f"{v:.8g}" for v in values) + "}"
        name = json.dumps(p["model"])
        lines.append("{" + name + ", " + name + ", " + matrix(p["cm1"]) + ", " + matrix(p["cm2"]) +
                     f', {p["illuminants"][0]}, {p["illuminants"][1]}, 0, false' + "},")
    (repository / "src/camera_profiles_extra.inc").write_text("\n".join(lines) + "\n", encoding="utf-8")
    receipt = dict(source="Installed Adobe Standard Nikon DCP metadata", exported_tags=[50708,50721,50722,50778,50779],
                   profiles=list(imported.values()), excluded_non_rgb=skipped)
    (repository / "src/camera_profiles_extra.json").write_text(json.dumps(receipt, indent=2) + "\n", encoding="utf-8")
    names = sorted([*known.values(), *(p["model"] for p in imported.values())], key=str.upper)
    document = ["# Nikon RGB calibration catalog", "",
                f"The bundled catalog contains **{len(names)} RGB camera calibrations**.", "",
                "A listed calibration is not a claim that every capture mode was tested. Native input",
                "must contain a supported RGB Bayer mosaic. CMYG and RGB small-raw modes are excluded.",
                "See [format support and validation](raw-formats.md). Existing sample-verified entries",
                "are retained; additional matrices come from local Adobe Standard DCP metadata.", "",
                "Additional profiles do not invent a camera BaselineExposure value; its DNG default applies.", ""]
    document.extend("- " + name for name in names)
    document += ["", "Regenerate additional entries using `python tools/import_nikon_calibrations.py PATH_TO_ADOBE_STANDARD`.",
                 "Only numerical calibration metadata is extracted. Original profile files and LUTs are not shipped."]
    (repository / "docs/nikon-cameras.md").write_text("\n".join(document) + "\n", encoding="utf-8")
    print(f"Added {len(imported)} RGB calibrations; catalog {len(names)} models; excluded {len(skipped)} non-RGB profiles")


if __name__ == "__main__":
    main()
